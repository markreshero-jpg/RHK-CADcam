// ============================================================
// Part cut-outs (z_rangehood/RANGEHOOD-SPEC.md, R1).
//
// Any part on a cabinet can carry cut-outs, keyed by its part id on the
// cabinet (`cabinet_instances.part_cutouts`, `case_bottom` / `int_fixed_shelf_0`
// → Cutout[], the ids partShapes and the formula engine use):
//   hole   a closed loop inside the part (rect / rounded rect / circle),
//          through or a pocket `depth` deep — becomes the resolved part's
//          `cutouts` (the same loops the curved-end rib cut-outs use), so
//          nesting, G-code, 3D and the cabinet views pick it up unchanged.
//   notch  a rectangle open to an edge, cut into the part's outline (R2).
//
// So far: the carcass's horizontal parts (bottom, top, rails), shelves, gables +
// shaped uprights + the flue box (holes only on gables, duct runs),
// flat custom parts (their own `cabinet_custom_parts.part_cutouts`, R3) and
// drawer box bottoms (`db_<r>_<c>_db_bottom`, R11 — plumbing U cut-outs).
// Positions are in the horizontal shape frame — x across from the part's left
// end (0..DY), y back from its front edge (0..DX).
// ============================================================

import { sampleOutline, type OutlinePt } from './shapePath'
import { evaluateFormula, type FormulaScope } from './formula'
import type { ResolvedCabinet } from './resolver/types'
import { dbPartId, type StackRef } from './cabinetShape/partKeys'

export type CutoutKind  = 'hole' | 'notch'
export type CutoutShape = 'rect' | 'circle'
export type CutoutAnchorX = 'left' | 'centre' | 'right'
export type CutoutAnchorY = 'front' | 'centre' | 'back'
/** A plain number, or a formula (z_formulas grammar: cab. / t. / r. / part("…")). */
export type CutoutValue = number | string

export interface Cutout {
  id:      string
  kind:    CutoutKind
  shape:   CutoutShape
  w:       CutoutValue           // across the part (circle: the diameter)
  d:       CutoutValue           // back from the front (ignored for a circle)
  radius?: number                // hole: rect corners · notch: its two inner corners (0 = square)
  // Where it sits: measured from this side of the part to the same side of the
  // cut-out (centre → centre to centre), + = in toward the middle / right / back.
  x: { from: CutoutAnchorX; off: CutoutValue }
  y: { from: CutoutAnchorY; off: CutoutValue }
  edge?:   'front' | 'back' | 'left' | 'right'   // notch: the edge it opens to
  depth?:  number | null         // hole: null = through, else pocket depth
  // Who made it: 'user' (edited in the list) or generated by another module
  // (the rangehood block, a WUP picking it up from the cabinet above) — read-only in the list.
  source?: 'user' | 'rangehood' | 'linked'
}

export type PartCutouts = Record<string, Cutout[]>

const num = (v: unknown, d = 0) => { const n = Number(v); return Number.isFinite(n) ? n : d }
const val = (v: unknown): CutoutValue => typeof v === 'string' && v.trim() !== '' && !Number.isFinite(Number(v)) ? v.trim() : num(v)

/** Stored jsonb → clean cut-outs; anything malformed is dropped. */
export function normalisePartCutouts(raw: unknown): PartCutouts {
  if (!raw || typeof raw !== 'object' || Array.isArray(raw)) return {}
  const out: PartCutouts = {}
  for (const [key, list] of Object.entries(raw as Record<string, unknown>)) {
    if (!Array.isArray(list)) continue
    const cs: Cutout[] = []
    list.forEach((c, i) => {
      if (!c || typeof c !== 'object') return
      const o = c as Record<string, unknown>
      const x = (o.x ?? {}) as Record<string, unknown>, y = (o.y ?? {}) as Record<string, unknown>
      const depth = o.depth == null ? null : num(o.depth)
      cs.push({
        id:     typeof o.id === 'string' && o.id ? o.id : `c${i + 1}`,
        kind:   o.kind === 'notch' ? 'notch' : 'hole',
        shape:  o.shape === 'circle' ? 'circle' : 'rect',
        w:      val(o.w),
        d:      val(o.d),
        radius: Math.max(0, num(o.radius)),
        x: { from: x.from === 'left' || x.from === 'right' ? x.from : 'centre', off: val(x.off) },
        y: { from: y.from === 'front' || y.from === 'back' ? y.from : 'centre', off: val(y.off) },
        ...(o.edge === 'front' || o.edge === 'back' || o.edge === 'left' || o.edge === 'right' ? { edge: o.edge } : {}),
        depth:  depth != null && depth > 0 ? depth : null,
        source: o.source === 'rangehood' || o.source === 'linked' ? o.source : 'user',
      })
    })
    if (cs.length) out[key] = cs
  }
  return out
}

/** A cut-out's numbers, formulas evaluated (no scope → formulas fail). */
export function cutoutNumbers(c: Cutout, scope?: FormulaScope): { w: number; d: number; xOff: number; yOff: number } | { error: string } {
  const get = (v: CutoutValue, what: string): number | string => {
    if (typeof v === 'number') return v
    if (!scope) return `${what}: formula needs the cabinet`
    const r = evaluateFormula(v, scope)
    return r.ok ? r.value : `${what}: ${r.error.message}`
  }
  const w = get(c.w, 'width'), d = c.shape === 'circle' ? w : get(c.d, 'depth')
  const xOff = get(c.x.off, 'x offset'), yOff = get(c.y.off, 'y offset')
  for (const v of [w, d, xOff, yOff]) if (typeof v === 'string') return { error: v }
  return { w: w as number, d: d as number, xOff: xOff as number, yOff: yOff as number }
}

/** Left / front corner of a w × d cut-out on a W × D part (horizontal shape frame). */
function place(c: Cutout, W: number, D: number, w: number, d: number, xOff: number, yOff: number) {
  const x0 = c.x.from === 'left' ? xOff : c.x.from === 'right' ? W - xOff - w : (W - w) / 2 + xOff
  const y0 = c.y.from === 'front' ? yOff : c.y.from === 'back' ? D - yOff - d : (D - d) / 2 + yOff
  return { x0, y0 }
}

const r2 = (v: number) => Math.round(v * 100) / 100

/** Closed loop of a hole, counter-clockwise, arcs as bulges (shapePath OutlinePt). */
export function holeLoop(x0: number, y0: number, w: number, d: number, shape: CutoutShape, radius = 0): OutlinePt[] {
  if (shape === 'circle') {
    const r = w / 2, cy = y0 + r
    return [{ x: r2(x0), y: r2(cy), b: 1 }, { x: r2(x0 + w), y: r2(cy), b: 1 }]
  }
  const x1 = x0 + w, y1 = y0 + d
  const rr = Math.min(Math.max(0, radius), w / 2, d / 2)
  if (rr < 0.01) return [{ x: r2(x0), y: r2(y0) }, { x: r2(x1), y: r2(y0) }, { x: r2(x1), y: r2(y1) }, { x: r2(x0), y: r2(y1) }]
  const B = Math.tan(Math.PI / 8)   // 90° corner
  const pts: OutlinePt[] = [
    { x: x0 + rr, y: y0 }, { x: x1 - rr, y: y0, b: B }, { x: x1, y: y0 + rr }, { x: x1, y: y1 - rr, b: B },
    { x: x1 - rr, y: y1 }, { x: x0 + rr, y: y1, b: B }, { x: x0, y: y1 - rr }, { x: x0, y: y0 + rr, b: B },
  ]
  // Square up a straight run that came out zero-length (rr = half the side).
  return pts.filter((p, i) => { const q = pts[(i + 1) % pts.length]; return Math.hypot(q.x - p.x, q.y - p.y) > 0.01 })
    .map(p => ({ ...p, x: r2(p.x), y: r2(p.y) }))
}

// ── Notches (R2) ──────────────────────────────────────────────────────────────

type Rect = { x0: number; x1: number; y0: number; y1: number }
const EPS = 0.01

/** Square-cornered (axis-aligned, no arcs) outline — the only kind R2 notches. */
function isRectilinear(pts: OutlinePt[]): boolean {
  return pts.every((p, i) => {
    const q = pts[(i + 1) % pts.length]
    return !(typeof p.b === 'number' && Math.abs(p.b) > 1e-9) && (Math.abs(p.x - q.x) < EPS || Math.abs(p.y - q.y) < EPS)
  })
}

function insidePoly(pts: OutlinePt[], x: number, y: number): boolean {
  let inside = false
  for (let i = 0, j = pts.length - 1; i < pts.length; j = i++) {
    const a = pts[i], b = pts[j]
    if ((a.y > y) !== (b.y > y) && x < (b.x - a.x) * (y - a.y) / (b.y - a.y) + a.x) inside = !inside
  }
  return inside
}

/**
 * `base` (a W × D rectangle when absent) less the notch rects, traced back to
 * one counter-clockwise outline. Square outlines only, so it works on a grid of
 * every x / y the shapes use: a cell is solid when its centre is inside the base
 * and in no notch. Edge tags on the base carry over to the edges left on them.
 * Null when the notches split the part (or leave nothing).
 */
export function notchOutline(W: number, D: number, base: OutlinePt[] | undefined, notches: Rect[]): OutlinePt[] | null {
  const poly = base ?? [{ x: 0, y: 0 }, { x: W, y: 0 }, { x: W, y: D }, { x: 0, y: D }]
  const uniq = (vs: number[]) => [...new Set(vs.map(r2))].sort((a, b) => a - b)
  const xs = uniq([...poly.map(p => p.x), ...notches.flatMap(n => [n.x0, n.x1])])
  const ys = uniq([...poly.map(p => p.y), ...notches.flatMap(n => [n.y0, n.y1])])
  const solid = (i: number, j: number) => {
    if (i < 0 || j < 0 || i >= xs.length - 1 || j >= ys.length - 1) return false
    const cx = (xs[i] + xs[i + 1]) / 2, cy = (ys[j] + ys[j + 1]) / 2
    return insidePoly(poly, cx, cy) && !notches.some(n => cx > n.x0 && cx < n.x1 && cy > n.y0 && cy < n.y1)
  }
  // Boundary edges of the solid cells, each running with the solid on its left.
  const next = new Map<string, { x: number; y: number }[]>()
  const key = (x: number, y: number) => `${x},${y}`
  let edges = 0
  const add = (ax: number, ay: number, bx: number, by: number) => {
    const k = key(ax, ay)
    next.set(k, [...(next.get(k) ?? []), { x: bx, y: by }])
    edges++
  }
  for (let i = 0; i < xs.length - 1; i++) for (let j = 0; j < ys.length - 1; j++) {
    if (!solid(i, j)) continue
    const x0 = xs[i], x1 = xs[i + 1], y0 = ys[j], y1 = ys[j + 1]
    if (!solid(i, j - 1)) add(x0, y0, x1, y0)
    if (!solid(i + 1, j)) add(x1, y0, x1, y1)
    if (!solid(i, j + 1)) add(x1, y1, x0, y1)
    if (!solid(i - 1, j)) add(x0, y1, x0, y0)
  }
  if (!edges) return null
  const first = next.keys().next().value as string
  const [sx, sy] = first.split(',').map(Number)
  const loop: { x: number; y: number }[] = []
  let cur = { x: sx, y: sy }
  for (let guard = 0; guard <= edges; guard++) {
    loop.push(cur)
    const outs = next.get(key(cur.x, cur.y))
    if (!outs?.length) return null
    cur = outs.shift()!
    if (cur.x === sx && cur.y === sy) break
  }
  if (loop.length !== edges) return null   // more than one loop: the part is split
  // Drop the grid points that sit mid-run.
  const pts = loop.filter((p, i) => {
    const a = loop[(i + loop.length - 1) % loop.length], b = loop[(i + 1) % loop.length]
    return !((a.x === p.x && p.x === b.x) || (a.y === p.y && p.y === b.y))
  })
  // Edge tags: an edge lying along a tagged base edge keeps its tag.
  const on = (a: OutlinePt, b: OutlinePt, u: { x: number; y: number }) =>
    Math.abs((b.x - a.x) * (u.y - a.y) - (b.y - a.y) * (u.x - a.x)) < EPS * Math.hypot(b.x - a.x, b.y - a.y)
    && u.x >= Math.min(a.x, b.x) - EPS && u.x <= Math.max(a.x, b.x) + EPS
    && u.y >= Math.min(a.y, b.y) - EPS && u.y <= Math.max(a.y, b.y) + EPS
  return pts.map((p, i) => {
    const q = pts[(i + 1) % pts.length]
    const src = poly.find((a, k) => !!a.e && on(a, poly[(k + 1) % poly.length], p) && on(a, poly[(k + 1) % poly.length], q))
    return src?.e ? { x: p.x, y: p.y, e: src.e } : { x: p.x, y: p.y }
  })
}

/**
 * A notch cut into one straight edge of a shaped outline (arcs elsewhere are
 * fine — z_curved_end C9: the flue notch in a curved former's straight back
 * edge). The notch must sit inside one straight, unbulged segment on its edge
 * line and clear every other part of the outline. Null when it can't.
 */
export function spliceNotch(pts: OutlinePt[], W: number, D: number, r: Rect, edge: 'front' | 'back' | 'left' | 'right'): OutlinePt[] | null {
  // Work with the edge as a line y = at (left / right: x ↔ y swapped, a mirror, so bulges flip).
  const swap = edge === 'left' || edge === 'right'
  const fwd = (p: OutlinePt): OutlinePt => swap ? { ...p, x: p.y, y: p.x, ...(p.b ? { b: -p.b } : {}) } : p
  const P = pts.map(fwd)
  const rr = swap ? { x0: r.y0, x1: r.y1, y0: r.x0, y1: r.x1 } : r
  const atMax = edge === 'back' || edge === 'right'
  const at = atMax ? (swap ? W : D) : 0
  const depth = atMax ? Math.min(at, rr.y1) - rr.y0 : rr.y1 - Math.max(0, rr.y0)
  const inner = atMax ? at - depth : depth
  const n = P.length
  for (let i = 0; i < n; i++) {
    const a = P[i], b = P[(i + 1) % n]
    if (a.b && Math.abs(a.b) > 1e-9) continue
    if (Math.abs(a.y - at) > EPS || Math.abs(b.y - at) > EPS) continue
    if (Math.min(a.x, b.x) > rr.x0 + EPS || Math.max(a.x, b.x) < rr.x1 - EPS) continue
    // Nothing else of the outline may reach into the notch.
    const bad = P.some((q, k) => k !== i && k !== (i + 1) % n
      && q.x > rr.x0 + EPS && q.x < rr.x1 - EPS && (atMax ? q.y > inner + EPS : q.y < inner - EPS))
    if (bad) return null
    // Board left both sides of the notch's inner edge, and the notch itself over
    // the part — true arcs (a chord cuts inside a convex curve: RHK6542's rail notch).
    const PS = sampleOutline(P, 1)
    const mid = (x: number) => insidePoly(PS, x, atMax ? inner - 0.5 : inner + 0.5)
    if (!mid(rr.x0 + 0.5) || !mid(rr.x1 - 0.5) || !insidePoly(PS, (rr.x0 + rr.x1) / 2, atMax ? (inner + at) / 2 : inner / 2)) return null
    const up = b.x > a.x
    const near = up ? rr.x0 : rr.x1, far = up ? rr.x1 : rr.x0
    const ins: OutlinePt[] = []
    const same = (u: OutlinePt, x: number, y: number) => Math.abs(u.x - x) < EPS && Math.abs(u.y - y) < EPS
    const aKeep: OutlinePt = same(a, near, at) ? { x: a.x, y: a.y } : a
    if (!same(a, near, at)) ins.push({ x: r2(near), y: r2(at) })
    ins.push({ x: r2(near), y: r2(inner) }, { x: r2(far), y: r2(inner) })
    if (!same(b, far, at)) ins.push({ x: r2(far), y: r2(at), ...(a.e ? { e: a.e } : {}) })
    const out = [...P.slice(0, i), aKeep, ...ins, ...P.slice(i + 1)]
    return out.map(fwd)   // the swap is its own inverse
  }
  return null
}

/**
 * Round one square corner of an outline (the point at cx, cy, straight edges
 * both sides) with a tangent arc of radius `rad` — a notch's inner corners (R11).
 * Concave corners get a clockwise arc (negative bulge), convex ones counter-clockwise.
 */
export function roundCorner(pts: OutlinePt[], cx: number, cy: number, rad: number): OutlinePt[] {
  const n = pts.length
  const i = pts.findIndex(p => Math.abs(p.x - cx) < EPS && Math.abs(p.y - cy) < EPS)
  if (i < 0 || rad < EPS) return pts
  const P = pts[i], A = pts[(i + n - 1) % n], B = pts[(i + 1) % n]
  if ((A.b && Math.abs(A.b) > 1e-9) || (P.b && Math.abs(P.b) > 1e-9)) return pts
  const la = Math.hypot(A.x - P.x, A.y - P.y), lb = Math.hypot(B.x - P.x, B.y - P.y)
  const rr = Math.min(rad, la, lb)
  if (rr < EPS) return pts
  const cross = (P.x - A.x) * (B.y - P.y) - (P.y - A.y) * (B.x - P.x)
  if (Math.abs(cross) < EPS) return pts
  const ang = Math.acos(Math.max(-1, Math.min(1, ((P.x - A.x) * (B.x - P.x) + (P.y - A.y) * (B.y - P.y)) / (la * lb))))
  const bulge = Math.sign(cross) * Math.tan(ang / 4)
  const p1: OutlinePt = { x: r2(P.x + (A.x - P.x) / la * rr), y: r2(P.y + (A.y - P.y) / la * rr), b: bulge }
  const p2: OutlinePt = { x: r2(P.x + (B.x - P.x) / lb * rr), y: r2(P.y + (B.y - P.y) / lb * rr), ...(P.e ? { e: P.e } : {}) }
  const out = [...pts.slice(0, i), p1, p2, ...pts.slice(i + 1)]
  // Two arcs meeting mid-edge (radius = half the notch width): drop the empty run.
  return out.filter((p, k) => {
    const q = out[(k + 1) % out.length]
    return !(Math.hypot(q.x - p.x, q.y - p.y) < EPS && !(p.b && Math.abs(p.b) > 1e-9))
  })
}

